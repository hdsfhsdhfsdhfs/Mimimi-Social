-- Mimimi social connections and profile visits
-- Safe to run more than once.

alter table public.profiles
  add column if not exists hide_profile_visitors boolean not null default false;

create table if not exists public.profile_follows (
  follower_id uuid not null references auth.users(id) on delete cascade,
  following_id uuid not null references auth.users(id) on delete cascade,
  created_at timestamptz not null default now(),
  primary key (follower_id, following_id),
  constraint profile_follows_no_self check (follower_id <> following_id)
);

create index if not exists profile_follows_following_idx
  on public.profile_follows(following_id, created_at desc);

create table if not exists public.profile_views (
  id bigint generated by default as identity primary key,
  profile_id uuid not null references auth.users(id) on delete cascade,
  viewer_id uuid not null references auth.users(id) on delete cascade,
  viewed_at timestamptz not null default now(),
  constraint profile_views_no_self check (profile_id <> viewer_id)
);

create index if not exists profile_views_profile_date_idx
  on public.profile_views(profile_id, viewed_at desc);

alter table public.profile_follows enable row level security;
alter table public.profile_views enable row level security;

drop policy if exists "Follows are publicly readable" on public.profile_follows;
create policy "Follows are publicly readable"
  on public.profile_follows for select to authenticated using (true);

drop policy if exists "Users can follow as themselves" on public.profile_follows;
create policy "Users can follow as themselves"
  on public.profile_follows for insert to authenticated
  with check (auth.uid() = follower_id and follower_id <> following_id);

drop policy if exists "Users can unfollow themselves" on public.profile_follows;
create policy "Users can unfollow themselves"
  on public.profile_follows for delete to authenticated
  using (auth.uid() = follower_id);

-- View rows are deliberately not directly readable from the client.
drop policy if exists "No direct profile view access" on public.profile_views;
create policy "No direct profile view access"
  on public.profile_views for select to authenticated using (false);

drop policy if exists "No direct profile view inserts" on public.profile_views;
create policy "No direct profile view inserts"
  on public.profile_views for insert to authenticated with check (false);

create or replace function public.record_profile_view(target_profile_id uuid)
returns void
language plpgsql
security definer
set search_path = ''
as $$
declare
  current_viewer uuid := auth.uid();
begin
  if current_viewer is null or target_profile_id is null or current_viewer = target_profile_id then
    return;
  end if;

  if not exists (
    select 1 from public.profile_views
    where profile_id = target_profile_id
      and viewer_id = current_viewer
      and viewed_at > now() - interval '30 minutes'
  ) then
    insert into public.profile_views(profile_id, viewer_id)
    values (target_profile_id, current_viewer);
  end if;
end;
$$;

create or replace function public.get_profile_social_stats(target_profile_id uuid)
returns jsonb
language plpgsql
security definer
set search_path = ''
as $$
declare
  is_private boolean := false;
  result jsonb;
begin
  select coalesce(p.hide_profile_visitors, false)
    into is_private
  from public.profiles p
  where p.auth_user_id = target_profile_id;

  select jsonb_build_object(
    'followers_count', (
      select count(*) from public.profile_follows f
      where f.following_id = target_profile_id
    ),
    'following_count', (
      select count(*) from public.profile_follows f
      where f.follower_id = target_profile_id
    ),
    'views_count', (
      select count(*) from public.profile_views v
      where v.profile_id = target_profile_id
    ),
    'is_following', (
      select exists (
        select 1 from public.profile_follows f
        where f.follower_id = auth.uid()
          and f.following_id = target_profile_id
      )
    ),
    'viewers', case
      when is_private and auth.uid() <> target_profile_id then '[]'::jsonb
      else coalesce((
        select jsonb_agg(jsonb_build_object(
          'auth_user_id', v.viewer_id,
          'display_name', p.display_name,
          'username', p.username,
          'avatar_url', p.avatar_url,
          'viewed_at', v.viewed_at
        ) order by v.viewed_at desc)
        from public.profile_views v
        join public.profiles p on p.auth_user_id = v.viewer_id
        where v.profile_id = target_profile_id
      ), '[]'::jsonb)
    end,
    'viewers_hidden', is_private
  ) into result;

  return result;
end;
$$;

grant execute on function public.record_profile_view(uuid) to authenticated;
grant execute on function public.get_profile_social_stats(uuid) to authenticated;


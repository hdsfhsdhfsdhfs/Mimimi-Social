-- Mimimi profile migration for bigint IDENTITY profiles.
-- Safe to re-run. Existing profile IDs are preserved.

alter table public.profiles
  add column if not exists auth_user_id uuid references auth.users(id) on delete cascade,
  add column if not exists bio text not null default '',
  add column if not exists avatar_url text,
  add column if not exists background_url text,
  add column if not exists is_official boolean not null default false,
  add column if not exists role_label text,
  add column if not exists role_description text,
  add column if not exists updated_at timestamptz not null default now();

create unique index if not exists profiles_auth_user_id_unique
  on public.profiles(auth_user_id)
  where auth_user_id is not null;

alter table public.profiles enable row level security;

drop policy if exists "Profiles are viewable by everyone" on public.profiles;
create policy "Profiles are viewable by everyone"
  on public.profiles for select using (true);

drop policy if exists "Users can create their own profile" on public.profiles;
create policy "Users can create their own profile"
  on public.profiles for insert to authenticated
  with check (auth.uid() = auth_user_id);

drop policy if exists "Users can update their own profile" on public.profiles;
create policy "Users can update their own profile"
  on public.profiles for update to authenticated
  using (auth.uid() = auth_user_id)
  with check (auth.uid() = auth_user_id);

-- Prevent normal users from granting themselves the official badge or staff role.
create or replace function public.protect_profile_staff_fields()
returns trigger
language plpgsql
set search_path = ''
as $$
begin
  if auth.uid() is not null then
    if tg_op = 'INSERT' then
      new.is_official := false;
      new.role_label := null;
      new.role_description := null;
    else
      new.is_official := old.is_official;
      new.role_label := old.role_label;
      new.role_description := old.role_description;
    end if;
  end if;
  return new;
end;
$$;

drop trigger if exists protect_profile_staff_fields on public.profiles;
create trigger protect_profile_staff_fields
before insert or update on public.profiles
for each row execute function public.protect_profile_staff_fields();

-- New signups get a profile row linked by auth_user_id; bigint id remains generated by IDENTITY.
create or replace function public.handle_new_user()
returns trigger
language plpgsql
security definer
set search_path = ''
as $$
begin
  insert into public.profiles (auth_user_id, display_name, username)
  values (
    new.id,
    coalesce(new.raw_user_meta_data ->> 'display_name', split_part(new.email, '@', 1)),
    null
  )
  on conflict (auth_user_id) where auth_user_id is not null do nothing;
  return new;
end;
$$;

drop trigger if exists on_auth_user_created on auth.users;
create trigger on_auth_user_created
after insert on auth.users
for each row execute procedure public.handle_new_user();

